class HybridCryptoError(Exception):
    """Базовое исключение для всей гибридной криптосистемы.
    
    Служит родительским классом для всех специфических исключений,
    возникающих при работе с криптографическими операциями.
    """
    pass


class SymmetricCryptoError(HybridCryptoError):
    """Исключение для ошибок при работе с симметричным шифрованием (AES).
    
    Возникает при проблемах с:
    - Генерацией симметричных ключей
    - Шифрованием/дешифрованием данных через AES
    - Валидацией размера ключа
    - Операциями с дополнением (padding)
    """
    pass


class AsymmetricCryptoError(HybridCryptoError):
    """Исключение для ошибок при работе с асимметричным шифрованием (RSA).
    
    Возникает при проблемах с:
    - Генерацией пар RSA-ключей
    - Сериализацией/десериализацией ключей
    - Шифрованием/дешифрованием сессионных ключей
    - Валидацией параметров RSA (размер ключа, экспонента)
    """
    pass
