"""
Модуль с иерархией исключений для гибридной криптосистемы.

Все исключения наследуются от базового CryptoSystemError,
что позволяет ловить их единым блоком или по отдельности.
"""


class CryptoSystemError(Exception):
    """
    Базовое исключение для всех ошибок криптосистемы.

    Атрибуты:
        message (str): Человекочитаемое описание ошибки.
    """

    def __init__(self, message:
    str = "Произошла ошибка в криптосистеме") -> None:
        """
        Инициализирует базовое исключение.

        Аргументы:
            message: Текст ошибки.
        """
        self.message = message
        super().__init__(self.message)


class ConfigError(CryptoSystemError):
    """
    Исключение, возникающее при ошибках конфигурации.

    Означает, что файл settings.json отсутствует, повреждён
    или не содержит обязательных ключей.
    """

    def __init__(self, message: str = "Ошибка конфигурации") -> None:
        """
        Инициализирует исключение конфигурации.

        Аргументы:
            message: Текст ошибки.
        """
        super().__init__(message)


class FileOperationError(CryptoSystemError):
    """
    Исключение, возникающее при ошибках файлового ввода-вывода.

    Означает, что файл не найден, нет прав на чтение/запись
    или файл имеет неверный формат.
    """

    def __init__(self, message: str = "Ошибка файловой операции") -> None:
        """
        Инициализирует исключение файловой операции.

        Аргументы:
            message: Текст ошибки.
        """
        super().__init__(message)


class KeyGenerationError(CryptoSystemError):
    """
    Исключение, возникающее при ошибках генерации ключей.

    Означает, что не удалось создать симметричный или
    асимметричный ключ.
    """

    def __init__(self, message: str = "Ошибка генерации ключей") -> None:
        """
        Инициализирует исключение генерации ключей.

        Аргументы:
            message: Текст ошибки.
        """
        super().__init__(message)


class EncryptionError(CryptoSystemError):
    """
    Исключение, возникающее при ошибках шифрования.

    Означает, что операция шифрования не удалась.
    """

    def __init__(self, message: str = "Ошибка шифрования") -> None:
        """
        Инициализирует исключение шифрования.

        Аргументы:
            message: Текст ошибки.
        """
        super().__init__(message)


class DecryptionError(CryptoSystemError):
    """
    Исключение, возникающее при ошибках расшифрования.

    Означает, что операция расшифрования не удалась,
    возможно, из-за неверного ключа или повреждённых данных.
    """

    def __init__(self, message: str = "Ошибка расшифрования") -> None:
        """
        Инициализирует исключение расшифрования.

        Аргументы:
            message: Текст ошибки.
        """
